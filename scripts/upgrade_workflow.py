"""Migrate exported workflow, preserving prompts, images, node IDs and settings."""

# Portable bootstrap: pythonXY._pth may omit the script directory.
# Add only this trusted package directory; never change global Python settings.
import sys as _sys
from pathlib import Path as _Path
_sys.path.insert(0, str(_Path(__file__).resolve().parent))
import argparse,copy,json,pathlib
from workflow_ui import beautify

ENCODER='qwen3vl_32b_minimax_h3-Q2_K_M.gguf'


def migrate_ui(workflow):
    w=copy.deepcopy(workflow)
    for n in w['nodes']:
        if n['type']=='H3ClipLoaderAny' and n.get('widgets_values',[None])[0]==ENCODER:
            n['type']='H3StudioNativeClipLoader'
            n['widgets_values']=[ENCODER]
            n['properties']={'Node name for S&R':'H3StudioNativeClipLoader'}
    # Notes generated by earlier versions can be regenerated without affecting execution.
    w['nodes']=[n for n in w['nodes'] if n['type']!='Note']
    maxid=max(n['id'] for n in w['nodes'])
    nextlink=max((l[0] for l in w['links']),default=0)+1
    for n in list(w['nodes']):
        if n['type']!='H3StudioReferences':continue
        existing=next((x for x in n.get('inputs',[]) if x['name']=='length'),None)
        if existing and existing.get('link') is not None:continue
        # v0.1 widgets: prompt, roles_json, width, height, length, ref_image_size.
        widgets=n.get('widgets_values',[])
        if len(widgets)<6:raise ValueError('Cannot infer frame widget; export the complete workflow JSON.')
        frames=int(widgets[4]);seconds=min(15.0,max(4.0,round(frames/24.0,1)))
        maxid+=1
        duration={'id':maxid,'type':'H3StudioDuration','pos':[930,260],'size':[610,190],'flags':{},
          'order':len(w['nodes']),'mode':0,'inputs':[],
          'outputs':[{'name':'Số frame hợp lệ','type':'INT','links':[nextlink]},
                     {'name':'Thời lượng thực (giây)','type':'FLOAT','links':[]}],
          'properties':{'Node name for S&R':'H3StudioDuration'},'widgets_values':[seconds]}
        w['nodes'].append(duration)
        if existing is None:
            existing={'name':'length','type':'INT','link':None,'widget':{'name':'length'}}
            n.setdefault('inputs',[]).append(existing)
        existing['link']=nextlink
        slot=n['inputs'].index(existing)
        w['links'].append([nextlink,maxid,0,n['id'],slot,'INT']);nextlink+=1
        # Widget order remains unchanged; the input's connected widget hides in frontend.
    w['last_link_id']=max((l[0] for l in w['links']),default=0)
    w['last_node_id']=maxid
    result=beautify(w)
    # Use semantic type for extra duration nodes whose IDs differ from the factory graph.
    for n in result['nodes']:
        if n['type']=='H3StudioDuration':
            n['title']='03 · THỜI LƯỢNG CLIP (GIÂY)';n['pos']=[930,260];n['size']=[610,190];n['flags']={}
    return result


def main():
    ap=argparse.ArgumentParser();ap.add_argument('workflow');a=ap.parse_args()
    path=pathlib.Path(a.workflow)
    w=json.loads(path.read_text(encoding='utf-8-sig'))
    if 'nodes' not in w:raise ValueError('Select a ComfyUI UI workflow export, not API JSON.')
    out=path.with_name(path.stem+'-VI-v0.2.json')
    if out.exists():raise FileExistsError('Output already exists: '+str(out))
    out.write_text(json.dumps(migrate_ui(w),ensure_ascii=False,indent=2),encoding='utf-8')
    print('Workflow mới:',out,'— file gốc không bị sửa.')
if __name__=='__main__':main()
